/**
 * 内置智能体角色（persona）。
 *
 * 这些是**提示词层面的角色**：选定后由 `TurnDirectiveComposer` 合成一段角色指令，
 * 让主循环以该角色的关注点与方法论推进——不是独立进程、不是另一套工具集。
 * 之所以不做成「真·多智能体」：真并行派生已有 `subagent` 工具与编排图（graph），
 * 而 UI 的「智能体」入口要解决的是「换个视角干活」，用角色指令达成即可，
 * 引入进程级派生只会让用户对一个下拉框的代价产生错误预期。
 *
 * 声明纪律：每个角色的 `directive` 必须写清「关注什么 + 交付什么 + 明确不做什么」，
 * 不允许写成「你很专业」这类无约束的空话。
 */

/** 内置智能体角色。 */
export interface AgentPersona {
  /** 稳定 id（UI 选项值）。 */
  readonly id: string;
  /** 展示名。 */
  readonly name: string;
  /** 一句话定位（下拉副标题）。 */
  readonly description: string;
  /** 注入回合的角色指令正文。 */
  readonly directive: string;
}

