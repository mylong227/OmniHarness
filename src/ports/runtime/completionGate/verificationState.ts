/**
 * 回合的**验证状态**（一等完成语义；2026-10-03 第六轮 G3-V2）。
 *
 * ## 为什么需要它
 *
 * 完成闸门（{@link CompletionGate}）在模型首次宣告完成时跑一次验证；若未通过，就把失败摘要回灌、
 * 再给一步。但**每回合至多一次**（有界设计，避免把步数预算烧在反复验证上）。于是当模型第二次宣告
 * 完成时，`TurnRunner` 只能放行——**而"放行"被上游读成了"验证通过"**：`AgentResult` 里没有任何字段
 * 表达"这一回合的核验并没有以通过收尾"。这正是假完成（false completion）在系统内的落点。
 *
 * 本类型把这件事变成一等状态，供上层（父会话 / 子代理 / 工作流 / UI）如实转达。
 *
 * ## 诚实边界（当前实现不区分「闸门通过」与「闸门未触发」）
 *
 * `CompletionGate.verify()` 返回 `string | undefined`，`undefined` 同时表示"通过"与"无需核验"
 * ⇒ 目前**无法**产出 `'passed'`。故本联合类型**不含** `'passed'`：与其造一个永远不出现的值，
 * 不如把口径写清。要让"通过"可区分，需把闸门契约改为返回富结果（`{ ran, ok, digest }`），
 * 属独立改动（已记入 `docs/ARCHITECTURE_UPGRADE_2026-10.md` 的后续项）。
 */
export type VerificationState =
  /** 本回合没有发生核验（未配置闸门，或闸门判定"无需核验"，例如本回合没改过源码）。 */
  | 'not-run'
  /** 核验**失败**且失败摘要已回灌给模型（本回合还给了一次机会）。 */
  | 'failed'
  /**
   * **模型二次宣告完成时仍未取得通过结论**（闸门本回合已用过一次、未再核验）。
   *
   * 语义要点：`'unverified'` **不得**被读成"验证通过"。它表示"这一回合以未核验通过收尾"——
   * 上层应据此保留怀疑（例如：不要把该回合的"已完成"当作已验证事实继续传播）。
   */
  | 'unverified';
