/**
 * 工作流步骤的**终态**（比 `ok` 布尔更细）。
 *
 * ## 为什么必须区分五种而非「成功/失败」
 *
 * 2026-10-08 把「受控条件执行」引入 DAG 引擎时暴露的语义问题：原先只有 `ok` 布尔，
 * 于是「**设计内跳过**（条件不满足）」与「**被上游拖死**（上游失败/取消）」在结果里长得一模一样，
 * 而两者的下游语义**必须相反**：
 * - `skipped`（条件不满足）：是作者写下的正常分支结果 ⇒ **不阻断下游**，整体仍可判成功；
 * - `blocked` / `cancelled`（上游失败/父取消）：是故障的传播 ⇒ **必须阻断下游**，整体判失败。
 *
 * 把两者混成一个 `ok:false` 的后果是：要么「补救步」永远跑不起来（被当故障传播），
 * 要么真故障被条件跳过掩盖（fail-open）——后者在本仓是不可接受的。
 *
 * 本文件只放**类型**：`src/ports/**` 是契约层，架构门禁禁止在端口层放实现
 * （2026-10-08 实测：把带方法的类放这里会被判「ports 纯度」违规）。判定与显示工具见
 * `autonomy/workflowStepStatuses.ts`。
 */
export type WorkflowStepStatus =
  /** 执行完成。 */
  | 'done'
  /** 执行了但失败。 */
  | 'failed'
  /** **设计内跳过**：`when` 条件不满足（不阻断下游）。 */
  | 'skipped'
  /** 未执行：上游失败导致（阻断下游，fail-closed 传播）。 */
  | 'blocked'
  /** 未执行：父会话取消（阻断下游）。 */
  | 'cancelled';
