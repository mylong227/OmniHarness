#!/usr/bin/env node
/**
 * Keep the published tarball lean without touching any source or build output.
 *
 * Measured on 0.4.0 (`npm pack --dry-run`): 19.37 MB / 4,222 files, of which
 * 12.22 MB is three documentation JPEGs and 11.56 MB is source maps (1,354
 * files). Neither is ever read by someone installing the package:
 *
 *   - `.map` files exist for debugging the *local* build; consumers run the
 *     shipped JS and never fetch them.
 *   - `docs/assets/*.jpg` are marketing/diagram images for the GitHub README;
 *     relative links inside `docs/*.md` keep working when browsing the repo.
 *   - `*.ttf` / `*.woff` are the legacy fallbacks of the KaTeX `@font-face`
 *     declarations, where `woff2` is the first supported source everywhere.
 *   - `docs/PROJECT_BOARD.md` is the internal development log, not consumer
 *     documentation.
 *
 * npm honours `.npmignore` in *sub*directories even when `files` is an
 * allowlist, so dropping these marker files into the build-output dirs is
 * enough. They live next to generated artifacts (gitignored, wiped by
 * `npm run clean`), so they are regenerated on demand instead of committed.
 *
 * Runs from `prepack`, i.e. for both `npm pack` and `npm publish`, after the
 * build steps in `prepublishOnly` have regenerated `dist` and `web/dist`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Build-output directories that ship, plus what must not travel with them. */
const RULES = [
  { dir: 'dist', patterns: ['*.map'], label: 'TypeScript source maps' },
  {
    dir: 'web/dist',
    patterns: ['*.map', '*.ttf', '*.woff'],
    label:
      'Vite source maps + legacy font formats (woff2 is the first supported @font-face source)',
  },
  {
    dir: 'docs/assets',
    patterns: ['*.jpg', '*.jpeg'],
    label: 'diagram images (kept in the repo, not in the tarball)',
  },
  {
    dir: 'docs',
    patterns: ['PROJECT_BOARD.md'],
    label: 'internal development board (not consumer documentation)',
  },
];

const HEADER = '# Generated by scripts/npmPackFilter.mjs — excluded from the published tarball.\n';

let written = 0;
for (const { dir, patterns, label } of RULES) {
  const target = path.join(root, dir);
  if (!fs.existsSync(target)) {
    console.warn(`npmPackFilter: skip ${dir} (not built yet)`);
    continue;
  }
  fs.writeFileSync(
    path.join(target, '.npmignore'),
    `${HEADER}# ${label}\n${patterns.join('\n')}\n`,
  );
  console.log(`npmPackFilter: ${dir}/.npmignore <- ${patterns.join(', ')}`);
  written += 1;
}

console.log(`npmPackFilter: ${String(written)} ignore file(s) in place`);
